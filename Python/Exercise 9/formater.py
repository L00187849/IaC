def convert_upper(my_text: str) -> str:
    """Convert text to upper case."""
    return my_text.upper()

def convert_lower(my_text: str) -> str:
    """Convert text to lower case."""
    return my_text.lower()

def convert_capital(my_text: str) -> str:
    """Convert text to capitalised form."""
    return my_text.capitalize()
