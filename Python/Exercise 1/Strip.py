# Purpose: Demonstrating the use of the strip() method to remove leading and trailing spaces.

# A string that contains extra spaces before and after the text
text_with_spaces = "     Liam Saunders     "

# strip() removes spaces from the beginning and end of the string
text_without_spaces = text_with_spaces.strip()

# Print the cleaned text
print(text_without_spaces)
