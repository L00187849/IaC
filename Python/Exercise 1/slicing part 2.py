# Purpose: Demonstrating how the + operator behaves differently with strings and integers.


# --- String concatenation example ---
first_character = "1"
second_character = "4"

# This joins the two strings into one: "1" + "4" → "14"
a = first_character + second_character
print(a)

# --- Integer addition example ---
first_number = 1
second_number = 2

# This performs numeric addition: 1 + 2 → 3
a = first_number + second_number
print(a)
